/**
 * The page a plugin's worker host loads (#2830): Minerva's own, served at
 * reserved paths on the plugin's origin (`frame-files.ts`), never the
 * plugin's. It does one thing: take the session port the host's preload
 * forwards, start the plugin's logic module in a Web Worker, and hand the
 * worker the port. Plugin code runs only in that worker — never in this page,
 * so never beside the preload — and talks to Minerva only over the port.
 *
 * The port is taken only from this window, on this origin; the module only
 * from this origin. The page's CSP (the frame CSP) allows scripts and workers
 * from the plugin's own origin and no network.
 */
import { PLUGIN_API_VERSION, PLUGIN_PORT_MESSAGE } from '../../shared/plugins/api';
import { WORKER_HOST_PORT_MESSAGE } from '../../shared/plugins/frame';

export const WORKER_HOST_HTML = `<!doctype html>
<meta charset="utf-8">
<title>Minerva plugin host</title>
<script src="/@minerva/worker-host.js"></script>
`;

export const WORKER_HOST_JS = `// Minerva's plugin worker host (#2830). Generated by Minerva; not plugin code.
window.addEventListener('message', function onPort(e) {
  if (e.source !== window || e.origin !== location.origin) return;
  if (!e.data || e.data.type !== ${JSON.stringify(WORKER_HOST_PORT_MESSAGE)} || !e.ports[0]) return;
  window.removeEventListener('message', onPort);
  const entry = new URL(String(e.data.entry), location.origin);
  if (entry.origin !== location.origin) return;
  const worker = new Worker(entry.href, { type: 'module' });
  worker.postMessage({ type: ${JSON.stringify(PLUGIN_PORT_MESSAGE)}, apiVersion: ${JSON.stringify(PLUGIN_API_VERSION)} }, [e.ports[0]]);
});
`;
