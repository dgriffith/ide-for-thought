// Resolve `t` (the tweak state) into an inline-style CSS-var map you can
// spread onto any artboard root, so each artboard gets the same look.
function tokenVars(t, mode /* 'dark' | 'light' */) {
  const pal = PALETTES[t.palette] || PALETTES.honey;
  const c = pal[mode];
  const type = TYPE_PAIRS[t.typePair] || TYPE_PAIRS.plex;
  const d = DENSITY[t.density] || DENSITY.cozy;
  return {
    "--bg": c.bg,
    "--bg-elev": c.bgElev,
    "--bg-elev-2": c.bgElev2,
    "--bg-inset": c.bgInset,
    "--text": c.text,
    "--text-muted": c.textMuted,
    "--text-faint": c.textFaint,
    "--border": c.border,
    "--border-strong": c.borderStrong,
    "--accent": c.accent,
    "--accent-dim": c.accentDim,
    "--accent-ink": c.accentInk,
    "--sage": c.sage,
    "--rust": c.rust,
    "--iris": c.iris,
    "--font-display": type.display,
    "--font-sans": type.sans,
    "--font-mono": type.mono,
    "--font-display-weight": type.displayWeight,
    "--font-ui-weight": type.uiWeight,
    "--row": `${d.row}px`,
    "--gap": `${d.gap}px`,
    "--pad": `${d.pad}px`,
    "--font-ui": `${d.font}px`,
    "--panel-h": `${d.panel}px`,
    background: c.bg,
    color: c.text,
    fontFamily: type.sans,
    fontWeight: type.uiWeight,
    fontSize: `${d.font}px`,
  };
}

window.MinervaTokens = { PALETTES, TYPE_PAIRS, DENSITY, tokenVars };
